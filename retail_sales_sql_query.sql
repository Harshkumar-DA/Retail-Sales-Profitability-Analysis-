use retail_sales ;
select count(*) from sales ;
select * from sales ;

/*1. Overall Business Performance
1. What is the total sales revenue generated by the company?
2. What is the total profit generated by the company?
3. How many unique orders were placed? */

select sum(sales) as total_sales
from sales;
select sum(profit) as total_sales
from sales;
select count(distinct order_id) as total_orders 
from sales ;

/*2. Sales & Profit Trends
4. What are the total sales and profit for each year?
5. Which year generated the highest sales?*/

select 
      year(order_date) as order_year,
      sum(sales) as total_sales,
      sum(profit) as total_profit
from sales 
group by year(order_date)
order by order_year ;
select 
      year(order_date) as order_year,
      sum(sales) as total_sales
from sales 
group by year(order_date)
order by order_year desc limit 1 ;
/*3. Product Analysis
7. Which product category generates the highest sales?
8. Which product category generates the highest profit?
9. What are the top 5 loss-making products?*/

SELECT
    Category,
    SUM(Sales) AS Total_Sales
FROM sales
GROUP BY Category
ORDER BY Total_Sales DESC;
SELECT
    Category,
    SUM(profit) AS Total_Sales
FROM sales
GROUP BY Category
ORDER BY Total_Sales DESC;
SELECT
    Product_Name,
    SUM(Profit) AS Total_Profit
FROM sales
GROUP BY Product_Name
HAVING SUM(Profit) < 0
ORDER BY Total_Profit ASC
LIMIT 5;

/*4. Regional Analysis
10. What are the total sales and profit for each region?
11. Which region generates the highest profit?
12. Are there any regions with high sales but low or negative profit?*/

SELECT
    Region,
    SUM(Sales) AS Total_Sales,
    ROUND(SUM(Profit), 2) AS Total_Profit
FROM sales
GROUP BY Region
ORDER BY Total_Sales DESC;
SELECT
    Region,
    SUM(Sales) AS Total_Sales,
    ROUND(SUM(Profit), 2) AS Total_Profit
FROM sales
GROUP BY Region
ORDER BY Total_Sales DESC limit 1 ;
SELECT
    Region,
    ROUND(SUM(Sales), 2) AS Total_Sales,
    ROUND(SUM(Profit), 2) AS Total_Profit
FROM sales
GROUP BY Region
having sum(profit) < 0 
ORDER BY Total_Sales DESC;

/*5. Discount & Customer Analysis
13. Do orders with higher discounts tend to generate lower profits?
14. Which customer segment contributes the highest profit?*/

select discount,
       sum(profit) as low_profit,
       count(order_id) as total_order
from sales
group by discount
order by discount desc;

select segment,
       sum(profit) as total_profit
from sales
group by segment
order by total_profit desc ;
